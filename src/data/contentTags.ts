import type { TopicKey } from './topics';

// [id prefix, first number, last number, ...topics]: ids are prefix-number, e.g. pol-1 to pol-8.
type Range = readonly [string, number, number, ...TopicKey[]];

export function expand(ranges: Range[]): Record<string, TopicKey[]> {
  const out: Record<string, TopicKey[]> = {};
  for (const [prefix, from, to, ...topics] of ranges) {
    for (let n = from; n <= to; n++) out[`${prefix}-${n}`] = topics;
  }
  return out;
}

